SET NAMES utf8mb4;

-- 1) Drop (detail first because of the foreign key)
DROP TABLE IF EXISTS BLOOMBUDDY_DAILY_CASH_BOOK_DETAIL;
DROP TABLE IF EXISTS BLOOMBUDDY_DAILY_CASH_BOOK;

-- 2) Header table with the new structure
CREATE TABLE BLOOMBUDDY_DAILY_CASH_BOOK (
    DAILY_CASH_BOOK_ID           BIGINT AUTO_INCREMENT PRIMARY KEY,
    CLIENT_ID                    BIGINT        NOT NULL,
    CLIENT_USERNAME              VARCHAR(100)  NOT NULL,
    BOOK_DATE                    DATE          NOT NULL,

    -- MANUAL (dynamic, driven by FIELD_CONFIG)
    MANUAL_DEBIT_TOTAL           DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    MANUAL_CREDIT_TOTAL          DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    MANUAL_DEBIT_VALUES          VARCHAR(2000) NULL,   -- Label=Amount&&Label=Amount
    MANUAL_CREDIT_VALUES         VARCHAR(2000) NULL,

    -- SYSTEM CALCULATED
    BUYER_PURCHASE_TOTAL         DECIMAL(12,2) DEFAULT 0.00,   -- Block 1
    FARMER_EXCESS_DEBIT_CASH     DECIMAL(12,2) DEFAULT 0.00,   -- Block 2
    BUYER_RECEIVED_TOTAL         DECIMAL(12,2) DEFAULT 0.00,   -- Block 3
    COMMISSION_TOTAL             DECIMAL(12,2) DEFAULT 0.00,   -- Block 4
    INSTALLMENT_TOTAL            DECIMAL(12,2) DEFAULT 0.00,   -- Block 5
    FARMER_EXCESS_DEBIT_NONCASH  DECIMAL(12,2) DEFAULT 0.00,   -- Block 6 (record only)

    -- TOTALS
    TOTAL_DEBIT_SIDE             DECIMAL(12,2) DEFAULT 0.00,
    TOTAL_CREDIT_SIDE            DECIMAL(12,2) DEFAULT 0.00,
    CLOSING_BALANCE              DECIMAL(12,2) DEFAULT 0.00,

    REMARKS                      VARCHAR(500) NULL,
    CREATED_BY                   VARCHAR(100),
    CREATED_DATE                 DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY                   VARCHAR(100),
    UPDATED_DATE                 DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT uq_daily_cash_book_client_date UNIQUE (CLIENT_ID, BOOK_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
-- The unique key already indexes (CLIENT_ID, BOOK_DATE), so no extra index is needed.

-- 3) Detail table (same as before, uppercase names)
CREATE TABLE BLOOMBUDDY_DAILY_CASH_BOOK_DETAIL (
    CASH_BOOK_DETAIL_ID   BIGINT AUTO_INCREMENT PRIMARY KEY,
    DAILY_CASH_BOOK_ID    BIGINT        NOT NULL,
    CLIENT_ID             BIGINT        NOT NULL,
    CLIENT_USERNAME       VARCHAR(100)  NOT NULL,
    BOOK_DATE             DATE          NOT NULL,
    ENTRY_TYPE            VARCHAR(40)   NOT NULL,   -- FARMER_EXCESS_DEBIT_CASH / FARMER_EXCESS_DEBIT_NONCASH
    ENTRY_LABEL           VARCHAR(150)  NOT NULL,
    FARMER_ID             VARCHAR(100)  NULL,
    AMOUNT                DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    DISPLAY_ORDER         INT DEFAULT 0,
    CREATED_DATE          DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_DATE          DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT fk_cash_book_detail_header
        FOREIGN KEY (DAILY_CASH_BOOK_ID)
        REFERENCES BLOOMBUDDY_DAILY_CASH_BOOK (DAILY_CASH_BOOK_ID)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE INDEX idx_cash_book_detail_header
    ON BLOOMBUDDY_DAILY_CASH_BOOK_DETAIL (DAILY_CASH_BOOK_ID, ENTRY_TYPE);

    SET NAMES utf8mb4;

CREATE TABLE BLOOMBUDDY_DAILY_CASH_BOOK_FIELD_CONFIG (
    FIELD_CONFIG_ID   BIGINT AUTO_INCREMENT PRIMARY KEY,
    CLIENT_ID         BIGINT        NOT NULL,
    CLIENT_USERNAME   VARCHAR(100)  NOT NULL,
    FIELD_LABEL       VARCHAR(50)   NOT NULL,            -- primary label, also the key stored in the cash book values string
    FIELD_LABEL_TA    VARCHAR(100)  NULL,                -- optional Tamil display label
    FIELD_TYPE        VARCHAR(10)   NOT NULL,            -- 'DEBIT' = Outgoing (left), 'CREDIT' = Incoming (right)
    DISPLAY_ORDER     INT           NOT NULL DEFAULT 0,
    CREATED_BY        VARCHAR(100),
    CREATED_DATE      DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY        VARCHAR(100),
    UPDATED_DATE      DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT uq_cb_field_client_type_label UNIQUE (CLIENT_ID, FIELD_TYPE, FIELD_LABEL),
    CONSTRAINT chk_cb_field_type CHECK (FIELD_TYPE IN ('DEBIT', 'CREDIT'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE INDEX idx_cb_field_client
    ON BLOOMBUDDY_DAILY_CASH_BOOK_FIELD_CONFIG (CLIENT_ID, FIELD_TYPE, DISPLAY_ORDER);