SET NAMES utf8mb4;

-- Farmer commission percentage (one global value per client)
DROP TABLE IF EXISTS BLOOMBUDDY_FARMER_COMMISSION_PERCENTAGE;

CREATE TABLE BLOOMBUDDY_FARMER_COMMISSION_PERCENTAGE (
    COMMISSION_CONFIG_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    CLIENT_ID           BIGINT        NOT NULL,
    CLIENT_USERNAME     VARCHAR(100)  NOT NULL,
    COMMISSION_PERCENT  DECIMAL(5,2)  NOT NULL DEFAULT 10.00,
    DESCRIPTION         VARCHAR(255)  NULL,
    CREATED_BY          VARCHAR(100)  NULL,
    CREATED_DATE        DATETIME      NULL,
    UPDATED_BY          VARCHAR(100)  NULL,
    UPDATED_DATE        DATETIME      NULL,

    CONSTRAINT UK_CLIENT_COMMISSION UNIQUE (CLIENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
